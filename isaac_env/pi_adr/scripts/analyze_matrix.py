"""A-G experimental matrix at n<=5 seeds (42,123,7,1,2), 800-iter protocol, frozen metrics v1.0.0.

Writes results/MATRIX_A_to_G.md. Exact two-sided permutation tests on difference of means for
pre-declared contrasts. Leads with mean error and worst decile (tail), then 5cm/2cm/1cm success.
Rungs: A human/no-DR, B Eureka/no-DR, C human/static DR, D Eureka/RAPP static DR,
E Eureka/adaptive DR/no RAPP, F4 Eureka/RAPP/adaptive DR, G F4 + frozen-PINN step multiplier,
Gp = G with shuffled multipliers (placebo).
"""
import itertools, json, os, statistics as st
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")
SEEDS = (42, 123, 7, 1, 2)
EXTRA = (3, 4, 5, 6, 8)  # G vs placebo retest, pre-declared 12 Oct: DRshift, worst-decile error
VARIANTS = ("nominal", "DRtrain", "DRshift")

def names(rung, v):
    if rung == "A": return [f"vanilla_seed{s}_800iter_{v}" if s in (42, 123, 7) else f"vanilla_ent0.005_seed{s}_800iter_{v}" for s in SEEDS]
    if rung == "B": return [f"eureka_seed{s}_800iter_{v}" for s in SEEDS]
    if rung == "C": return [f"C_human_static_dr_{v}" if s == 42 else f"C_seed{s}_human_static_dr_{v}" for s in SEEDS]
    if rung == "D": return [f"D_{v}" if s == 42 else f"D_seed{s}_{v}" for s in SEEDS]
    if rung == "E": return [f"E_adaptive_no_rapp_{v}" if s == 42 else f"E_seed{s}_no_rapp_{v}" for s in SEEDS]
    if rung == "F4": return [f"F4_{v}" if s == 42 else f"F4_seed{s}_{v}" for s in SEEDS]
    if rung == "G": return [f"G_seed{s}_{v}" for s in SEEDS]
    if rung == "Gp": return [f"Gplacebo_seed{s}_{v}" for s in SEEDS]

METRICS = {
    "mean err (mm)": lambda d: d["mean_terminal_error_m"] * 1000,
    "worst10% (mm)": lambda d: d["worst_decile_error_m"] * 1000,
    "5cm %": lambda d: d["success_rate"]["0.05"] * 100,
    "2cm %": lambda d: d["success_rate"]["0.02"] * 100,
    "1cm %": lambda d: d["success_rate"]["0.01"] * 100,
}
RUNGS = ("A", "B", "C", "D", "E", "F4", "G", "Gp")
CONTRASTS = [("B", "A"), ("C", "A"), ("D", "B"), ("D", "C"), ("E", "D"), ("F4", "D"), ("F4", "E"), ("G", "F4"), ("G", "Gp"), ("G", "D")]

def load(n):
    p = os.path.join(R, n + ".json")
    return json.load(open(p)) if os.path.exists(p) else None

def vals(rung, v, f):
    return [f(d) for d in (load(n) for n in names(rung, v)) if d]

def perm_p(a, b):
    pool = a + b; n = len(a); obs = abs(st.mean(a) - st.mean(b)); cnt = tot = 0
    for idx in itertools.combinations(range(len(pool)), n):
        ga = [pool[i] for i in idx]; gb = [pool[i] for i in range(len(pool)) if i not in idx]
        tot += 1; cnt += abs(st.mean(ga) - st.mean(gb)) >= obs - 1e-12
    return cnt / tot

out = ["# A-G matrix (800-iter protocol, frozen metrics v1.0.0, seeds 42/123/7/1/2)\n",
       "Mean ± std across seeds; n = number of completed seeds. Generated by `scripts/analyze_matrix.py`.\n"]
for v in VARIANTS:
    out.append(f"\n## Evaluation: {v}\n")
    out.append("| rung | n | " + " | ".join(METRICS) + " |\n|---|---|" + "---|" * len(METRICS))
    for r in RUNGS:
        cells, n = [], 0
        for m, f in METRICS.items():
            x = vals(r, v, f); n = len(x)
            cells.append(f"{st.mean(x):.2f} ± {st.stdev(x):.2f}" if len(x) > 1 else (f"{x[0]:.2f}" if x else "—"))
        out.append(f"| {r} | {n} | " + " | ".join(cells) + " |")
    out.append(f"\nPermutation p (two-sided exact), X vs Y on {v}:\n")
    out.append("| contrast | " + " | ".join(METRICS) + " |\n|---|" + "---|" * len(METRICS))
    for x, y in CONTRASTS:
        cells = []
        for m, f in METRICS.items():
            a, b = vals(x, v, f), vals(y, v, f)
            cells.append(f"{st.mean(a)-st.mean(b):+.2f} (p={perm_p(a,b):.3f})" if len(a) >= 3 and len(b) >= 3 and len(a) == len(b) else "n/a")
        out.append(f"| {x} − {y} | " + " | ".join(cells) + " |")
open(os.path.join(R, "MATRIX_A_to_G.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
